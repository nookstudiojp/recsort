import assert from 'node:assert/strict';
import {decisionKey,getDecision,canSelect,readDecisions,setDecision} from './dist/decisions.mjs';
import {makeCSV,demoRecords} from './dist/core.mjs';
const record=demoRecords(1793664000000)[0];
let decisions=readDecisions(null);
assert.equal(getDecision(record,decisions),'none');
decisions=setDecision(record,decisions,'keep');
assert.equal(canSelect(record,decisions),false);
assert.equal(getDecision({...record},readDecisions(JSON.stringify(decisions))),'keep');
assert.equal(getDecision({...record,size:record.size+1},decisions),'none');
assert.equal(getDecision({...record,modified:record.modified+1},decisions),'none');
decisions=setDecision(record,decisions,'later');
assert.equal(canSelect(record,decisions),true);
assert.ok(makeCSV([record],90,2,1793664000000,decisions).includes('あとで確認'));
decisions=setDecision(record,decisions,'none');
assert.equal(Object.keys(decisions).length,0);
assert.equal(Object.keys(readDecisions('broken')).length,0);
assert.equal(Object.keys(readDecisions('{"__proto__":"keep","bad":"keep"}')).length,0);
assert.ok(decisionKey(record).includes(record.path));
console.log('11 decision and CSV assertions passed');
